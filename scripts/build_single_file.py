# -*- coding: utf-8 -*-
"""Build the self-contained single-file distribution macro.

Combines ``src/ListVarSetPropertyReferences_dev.FCMacro`` (GUI layer) and
``src/varset_usage_core_dev.py`` (headless logic) into ONE file at the
PROJECT ROOT: ``ListVarSetPropertyReferences.FCMacro``:

* the full core source is embedded as the ``_EMBEDDED_CORE_SOURCE`` raw
  string literal between the EMBEDDED CORE markers; the macro's loader
  prefers that copy over any sibling file, so the distributed artifact
  needs nothing but itself (community convention: one file to drop into
  the Macro folder -- see research/MACRO_CONVENTIONS.md);
* an official metadata header (``__Name__``, ``__Version__``, ... as used
  by github.com/FreeCAD/FreeCAD-macros) is inserted after the module
  docstring so Addon Manager installs pick it up.

The development layout (two files side by side in src/) stays the source
of truth; this script only generates. Re-run it whenever either input
changes. The output lands at the project root on purpose: the top level
holds the deliverable, src/ holds the sources.

Run:  python scripts\\build_single_file.py
Exits non-zero on any verification failure.
"""

import ast
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEV_MACRO = os.path.join(ROOT, "src", "ListVarSetPropertyReferences_dev.FCMacro")
CORE = os.path.join(ROOT, "src", "varset_usage_core_dev.py")
OUT = os.path.join(ROOT, "ListVarSetPropertyReferences.FCMacro")

BEGIN_MARK = "# === BEGIN EMBEDDED CORE (generated by scripts/build_single_file.py) ==="
END_MARK = "# === END EMBEDDED CORE ==="

METADATA = '''\
__Name__ = "List VarSet Property References"
__Comment__ = ("Lists every expression referencing a selected VarSet "
               "property across all open documents; flags dead "
               "cross-document references.")
__Author__ = "Marc Christensen <mecworks@gmail.com>"
__Copyright__ = "(c) 2026 Marc Christensen"
__Version__ = "1.2.0"
__Date__ = "2026-11-15"
__License__ = "LGPL-2.1-or-later"
__Web__ = ""
__Icon__ = ""
__Help__ = ("Pick a VarSet and one of its properties; lists expressions "
            "referencing it in the active document and (by default) every "
            "other open document. Lines prefixed with (!) reference a "
            "document that is not open (dead binding).")
__Status__ = "Stable"
__Requires__ = "FreeCAD >= 1.1"
'''

BANNER = '''\
#
# GENERATED single-file distribution build -- do not edit by hand.
# Source of truth: src/ListVarSetPropertyReferences_dev.FCMacro
#                  + src/varset_usage_core_dev.py
# Regenerate with:  python scripts\\build_single_file.py
#
'''


def _read(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def _embed_block(core_src):
    """Return the literal that embeds *core_src*, byte-exact."""
    if "'''" in core_src:
        raise ValueError("core source contains ''' -- cannot embed safely")
    if core_src.rstrip("\n").endswith("\\"):
        raise ValueError("core source ends with a backslash -- unsafe in a "
                         "raw string literal")
    compile(core_src, "varset_usage_core_dev", "exec")  # must be valid Python
    # No padding newlines: the raw-string value IS core_src, byte for byte.
    return "_EMBEDDED_CORE_SOURCE = r'''" + core_src + "'''"


def _docstring_end_index(lines):
    """Index of the line closing the module docstring ('""')."""
    seen_open = False
    for i, line in enumerate(lines):
        if line.strip() == '"""':
            if seen_open:
                return i
            seen_open = True
    raise ValueError("module docstring not found in dev macro")


def build(root=ROOT):
    """Generate the single-file build; returns the output path."""
    dev = _read(os.path.join(root, "src",
                             "ListVarSetPropertyReferences_dev.FCMacro"))
    core_src = _read(os.path.join(root, "src", "varset_usage_core_dev.py"))

    begin_i = dev.index(BEGIN_MARK)
    end_j = dev.index(END_MARK)
    if end_j < begin_i:
        raise ValueError("EMBEDDED CORE markers out of order")
    block = _embed_block(core_src)
    body = (dev[:begin_i] + block + "\n" + dev[end_j:])

    lines = body.split("\n")
    ins = _docstring_end_index(lines) + 1
    meta_lines = BANNER.lstrip("\n").rstrip("\n").split("\n")
    meta_lines += METADATA.rstrip("\n").split("\n")
    lines[ins:ins] = meta_lines

    out_path = os.path.join(root, "ListVarSetPropertyReferences.FCMacro")
    generated = "\n".join(lines)
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(generated)
    return out_path


def _extract_embedded(source):
    """Pull _EMBEDDED_CORE_SOURCE back out of *source* via AST."""
    tree = ast.parse(source)
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if (isinstance(target, ast.Name)
                        and target.id == "_EMBEDDED_CORE_SOURCE"):
                    return node.value.value
    return None


def verify(root=ROOT):
    """Independent checks on the generated file. Returns list of failures."""
    failures = []
    gen_path = os.path.join(root, "ListVarSetPropertyReferences.FCMacro")
    if not os.path.isfile(gen_path):
        return ["generated file missing: {}".format(gen_path)]
    generated = _read(gen_path)
    core_src = _read(os.path.join(root, "src", "varset_usage_core_dev.py"))

    try:
        ast.parse(generated)
    except SyntaxError as exc:
        failures.append("generated file does not parse: {}".format(exc))
        return failures

    embedded = _extract_embedded(generated)
    if embedded != core_src:
        failures.append(
            "embedded core is not byte-identical to "
            "src/varset_usage_core_dev.py "
            "({} vs {} chars)".format(
                len(embedded) if embedded is not None else -1,
                len(core_src)))

    for field in ("__Name__", "__Version__", "__License__", "__Requires__"):
        if "{} = ".format(field) not in generated:
            failures.append("metadata field missing: {}".format(field))
    return failures


def main():
    out = build()
    print("built: {}".format(out))
    failures = verify()
    for f in failures:
        print("FAIL: {}".format(f))
    if failures:
        return 1
    print("verify: embedded core byte-identical, metadata present, parses OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
